#!/bin/bash

set -euo pipefail

echo "=========================================="
echo "Step9 PPO Full-Data Training"
echo "=========================================="

WORKDIR="$(cd "$(dirname "$0")/.." && pwd)"

# Full-data schedule.
# Dataset currently has 5000 samples.
# Default split:
# - train: 4750 (eval_ratio=0.05)
# - eval: 250
export NUM_SAMPLES="${NUM_SAMPLES:-5000}"
export EVAL_RATIO="${EVAL_RATIO:-0.05}"
export EVAL_MAX_SAMPLES="${EVAL_MAX_SAMPLES:-250}"
export EVAL_EVERY_ITERATIONS="${EVAL_EVERY_ITERATIONS:-1}"
export NUM_ITERATIONS="${NUM_ITERATIONS:-4}"
export EPISODES_PER_ITERATION="${EPISODES_PER_ITERATION:-0}"  # auto = train split size
export UPDATE_EVERY_EPISODES="${UPDATE_EVERY_EPISODES:-64}"
export MAX_ROUNDS="${MAX_ROUNDS:-5}"
export STOP_THRESHOLD="${STOP_THRESHOLD:-0.9}"
export SAVE_EVERY_ITERATIONS="${SAVE_EVERY_ITERATIONS:-1}"
export AUTO_RESUME_LATEST="${AUTO_RESUME_LATEST:-1}"

# Dedicated output path for long full-data runs.
export OUTPUT_DIR="${OUTPUT_DIR:-$WORKDIR/step9/output/ppo_model_full}"

# More conservative PPO settings than smoke test.
export LEARNING_RATE="${LEARNING_RATE:-3e-6}"
export BATCH_SIZE="${BATCH_SIZE:-1}"
export MINI_BATCH_SIZE="${MINI_BATCH_SIZE:-1}"
export GRADIENT_ACCUMULATION_STEPS="${GRADIENT_ACCUMULATION_STEPS:-32}"
export NUM_EPOCHS="${NUM_EPOCHS:-2}"
export CLIP_EPSILON="${CLIP_EPSILON:-0.15}"
export ENTROPY_COEF="${ENTROPY_COEF:-0.005}"
export TARGET_KL="${TARGET_KL:-0.05}"
export EARLY_STOP_KL="${EARLY_STOP_KL:-0.25}"
export WARMUP_STEPS="${WARMUP_STEPS:-200}"
export LR_SCHEDULER="${LR_SCHEDULER:-cosine}"

# Keep reward / generation defaults stable unless explicitly overridden.
export INITIAL_MAX_NEW_TOKENS="${INITIAL_MAX_NEW_TOKENS:-4096}"
export INITIAL_ACTION_MAX_EVAL_TOKENS="${INITIAL_ACTION_MAX_EVAL_TOKENS:-$INITIAL_MAX_NEW_TOKENS}"
export INITIAL_R_REWARD_SCALE="${INITIAL_R_REWARD_SCALE:-0.25}"
export ACTION_MAX_NEW_TOKENS="${ACTION_MAX_NEW_TOKENS:-512}"
export MAX_PROMPT_TOKENS="${MAX_PROMPT_TOKENS:-12000}"
export INITIAL_MAX_PROMPT_TOKENS="${INITIAL_MAX_PROMPT_TOKENS:-12000}"
export MAX_NEW_TOKENS="${MAX_NEW_TOKENS:-1024}"
export OPTIMIZE_INITIAL_KC="${OPTIMIZE_INITIAL_KC:-1}"

# Reward defaults aligned with current training environment.
export DELTA_POS_SCALE="${DELTA_POS_SCALE:-7.0}"
export DELTA_NEG_SCALE="${DELTA_NEG_SCALE:-5.0}"
export ROLLBACK_THRESHOLD="${ROLLBACK_THRESHOLD:-0.3}"
export ROLLBACK_EXTRA_PENALTY="${ROLLBACK_EXTRA_PENALTY:-1.5}"
export HIGH_SCORE_THRESHOLD="${HIGH_SCORE_THRESHOLD:-0.9}"
export HIGH_SCORE_STOP_BONUS="${HIGH_SCORE_STOP_BONUS:-0.8}"
export PREMATURE_STOP_PENALTY="${PREMATURE_STOP_PENALTY:-1.0}"
export HIGH_SCORE_CONTINUE_PENALTY="${HIGH_SCORE_CONTINUE_PENALTY:-0.15}"
export TEACHER_STOP_HIGH_SCORE_BONUS="${TEACHER_STOP_HIGH_SCORE_BONUS:-0.2}"
export STEP_PENALTY="${STEP_PENALTY:-0.002}"
export NO_PROGRESS_PENALTY="${NO_PROGRESS_PENALTY:-0.01}"
export NO_PROGRESS_EPS="${NO_PROGRESS_EPS:-0.001}"
export MAX_STAGNANT_ROUNDS="${MAX_STAGNANT_ROUNDS:-4}"
export POSITIVE_CORRECTION_BONUS="${POSITIVE_CORRECTION_BONUS:-0.15}"
export FINAL_SCORE_SCALE="${FINAL_SCORE_SCALE:-0.35}"
export INEFFECTIVE_TERMINATION_PENALTY="${INEFFECTIVE_TERMINATION_PENALTY:-0.15}"

# Keep the actual training prompt pack explicit.
export PROMPT_ROOT="${PROMPT_ROOT:-$WORKDIR/step9/prompt_packs/train_v1}"

# Single-card default on physical GPU1, same as smoke test.
export CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-1}"
export DEVICE_MAP="${DEVICE_MAP:-cuda:0}"
export REF_MODEL_DEVICE_MAP="${REF_MODEL_DEVICE_MAP:-$DEVICE_MAP}"
export ALLOW_SHARED_REF_DEVICE="${ALLOW_SHARED_REF_DEVICE:-1}"
export ENABLE_REF_MODEL="${ENABLE_REF_MODEL:-1}"

echo "Full-data defaults:"
echo "  NUM_SAMPLES=$NUM_SAMPLES"
echo "  EVAL_RATIO=$EVAL_RATIO"
echo "  EVAL_MAX_SAMPLES=$EVAL_MAX_SAMPLES"
echo "  NUM_ITERATIONS=$NUM_ITERATIONS"
echo "  EPISODES_PER_ITERATION=${EPISODES_PER_ITERATION} (0 means auto=train split size)"
echo "  UPDATE_EVERY_EPISODES=$UPDATE_EVERY_EPISODES"
echo "  LEARNING_RATE=$LEARNING_RATE"
echo "  CLIP_EPSILON=$CLIP_EPSILON"
echo "  ENTROPY_COEF=$ENTROPY_COEF"
echo "  TARGET_KL=$TARGET_KL"
echo "  EARLY_STOP_KL=$EARLY_STOP_KL"
echo "  GRADIENT_ACCUMULATION_STEPS=$GRADIENT_ACCUMULATION_STEPS"
echo "  OUTPUT_DIR=$OUTPUT_DIR"
echo "  PROMPT_ROOT=$PROMPT_ROOT"

exec bash "$WORKDIR/step9/run_ppo.sh"
