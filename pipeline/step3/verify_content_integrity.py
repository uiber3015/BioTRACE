"""
验证保存的JSON文件是否包含完整的markdown内容
"""
import json
from pathlib import Path


def load_json(file_path):
    """加载JSON文件"""
    with open(file_path, 'r', encoding='utf-8') as f:
        return json.load(f)


def load_markdown(file_path):
    """加载Markdown文件"""
    with open(file_path, 'r', encoding='utf-8') as f:
        return f.read()


def verify_sample_tables():
    """验证几个样本表格的内容完整性"""
    print("=" * 80)
    print("验证表格内容完整性")
    print("=" * 80)
    
    # 测试不同分类的第1个表格
    categories = ["all_in", "partial_in", "none_in"]
    base_dir = Path("data/step3/output")
    original_dir = Path("data/step1/output/table_markdown_1/")
    
    for category in categories:
        print(f"\n📂 检查 {category} 分类:")
        
        # 读取第1个JSON文件
        json_file = base_dir / category / "1.json"
        if not json_file.exists():
            print(f"  ⚠️  文件不存在: {json_file}")
            continue
        
        table_data = load_json(json_file)
        
        # 获取原始文件
        table_id = table_data.get("table_id")
        original_file = original_dir / f"{table_id}.md"
        
        if not original_file.exists():
            print(f"  ⚠️  原始文件不存在: {original_file}")
            continue
        
        # 读取原始内容
        original_content = load_markdown(original_file)
        saved_content = table_data.get("markdown_content", "")
        
        # 比较
        print(f"  表格ID: {table_id}")
        print(f"  原始文件大小: {len(original_content)} 字符")
        print(f"  保存文件大小: {len(saved_content)} 字符")
        
        if original_content == saved_content:
            print(f"  ✅ 内容完全一致！")
        else:
            print(f"  ❌ 内容不一致！")
            print(f"     差异: {abs(len(original_content) - len(saved_content))} 字符")
            
            # 检查具体缺失的部分
            if len(saved_content) < len(original_content):
                print(f"  缺失内容预览:")
                missing_start = len(saved_content)
                print(f"     原始内容第{missing_start}字符后: {original_content[missing_start:missing_start+100]}")
        
        # 检查关键部分是否存在
        print(f"\n  检查关键部分:")
        checks = {
            "# Table": "表格标题",
            "**Source:**": "来源信息",
            "**Page:**": "页码信息",
            "## Caption": "表格标题部分",
            "## Table Content": "表格内容部分",
            "## Mentioned in Text": "文本引用部分",
            "*Generated by RapidTable*": "生成信息"
        }
        
        for keyword, desc in checks.items():
            if keyword in saved_content:
                print(f"    ✅ {desc}: 存在")
            else:
                print(f"    ❌ {desc}: 缺失")
        
        # 显示所有字段
        print(f"\n  JSON包含的字段:")
        for key in table_data.keys():
            if key == "markdown_content":
                print(f"    - {key}: {len(table_data[key])} 字符")
            elif isinstance(table_data[key], list):
                print(f"    - {key}: {len(table_data[key])} 项")
            else:
                print(f"    - {key}: {str(table_data[key])[:50]}...")


def verify_random_samples():
    """随机抽查几个表格"""
    print("\n" + "=" * 80)
    print("随机抽查表格")
    print("=" * 80)
    
    base_dir = Path("data/step3/output")
    original_dir = Path("data/step1/output/table_markdown_1/")
    
    # 检查all_in的第10、100、1000个表格
    test_numbers = [10, 100, 1000]
    
    for num in test_numbers:
        json_file = base_dir / "all_in" / f"{num}.json"
        if not json_file.exists():
            continue
        
        table_data = load_json(json_file)
        table_id = table_data.get("table_id")
        original_file = original_dir / f"{table_id}.md"
        
        if original_file.exists():
            original_content = load_markdown(original_file)
            saved_content = table_data.get("markdown_content", "")
            
            match = "✅" if original_content == saved_content else "❌"
            print(f"{match} 表格 #{num} ({table_id}): {len(original_content)} vs {len(saved_content)} 字符")


def main():
    verify_sample_tables()
    verify_random_samples()
    
    print("\n" + "=" * 80)
    print("验证完成")
    print("=" * 80)


if __name__ == "__main__":
    main()
