"""
根据实体筛选结果，将表格按分类组织到不同文件夹
分类：全部在、部分在、全都不在
"""
import json
from pathlib import Path
from collections import defaultdict


def load_json(file_path):
    """加载JSON文件"""
    with open(file_path, 'r', encoding='utf-8') as f:
        return json.load(f)


def save_json(data, file_path):
    """保存JSON文件"""
    file_path.parent.mkdir(parents=True, exist_ok=True)
    with open(file_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=2, ensure_ascii=False)


def load_markdown(file_path):
    """加载Markdown文件 - 完整读取所有内容"""
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            content = f.read()
        # 验证内容完整性
        if not content or len(content) == 0:
            print(f"    ⚠️  警告: 文件为空 - {file_path}")
            return None
        return content
    except Exception as e:
        print(f"    ❌ 错误: 无法读取文件 - {file_path}: {e}")
        return None


def parse_markdown_table(markdown_content):
    """
    解析markdown表格内容，提取各个部分
    
    Returns:
        dict: 包含各个部分的字典
    """
    import re
    
    parsed = {
        "table_title": "",
        "source": "",
        "page": "",
        "table_identifier": "",
        "caption": "",
        "table_content": "",
        "mentioned_in_text": "",
        "references": [],
        "image_file": "",
        "generated_by": ""
    }
    
    # 1. 提取Table标题 (第一行 # Table XXXXX)
    title_match = re.search(r'^# Table (\d+)', markdown_content, re.MULTILINE)
    if title_match:
        parsed["table_title"] = f"Table {title_match.group(1)}"
    
    # 2. 提取Source
    source_match = re.search(r'\*\*Source:\*\*\s*(.+?)(?:\n|$)', markdown_content)
    if source_match:
        parsed["source"] = source_match.group(1).strip()
    
    # 3. 提取Page
    page_match = re.search(r'\*\*Page:\*\*\s*(.+?)(?:\n|$)', markdown_content)
    if page_match:
        parsed["page"] = page_match.group(1).strip()
    
    # 4. 提取Table Identifier
    identifier_match = re.search(r'\*\*Table Identifier:\*\*\s*(.+?)(?:\n|$)', markdown_content)
    if identifier_match:
        parsed["table_identifier"] = identifier_match.group(1).strip()
    
    # 5. 提取Caption (## Caption 到下一个 ## 之间的内容)
    caption_match = re.search(r'## Caption\s*\n\n(.*?)\n\n##', markdown_content, re.DOTALL)
    if caption_match:
        parsed["caption"] = caption_match.group(1).strip()
    
    # 6. 提取Table Content (## Table Content 到下一个 ## 之间的内容)
    table_content_match = re.search(r'## Table Content\s*\n\n(.*?)\n\n##', markdown_content, re.DOTALL)
    if table_content_match:
        parsed["table_content"] = table_content_match.group(1).strip()
    
    # 7. 提取Mentioned in Text (整个 ## Mentioned in Text 部分)
    mentioned_match = re.search(r'## Mentioned in Text\s*\n\n(.*?)(?:\n\n---|\n---)', markdown_content, re.DOTALL)
    if mentioned_match:
        parsed["mentioned_in_text"] = mentioned_match.group(1).strip()
    
    # 8. 提取所有References (### Reference N 部分)
    reference_pattern = r'### Reference (\d+)\s*\n\n(.*?)(?=### Reference|\n\n---|\Z)'
    references = re.findall(reference_pattern, markdown_content, re.DOTALL)
    if references:
        parsed["references"] = [
            {
                "reference_number": int(ref_num),
                "content": ref_content.strip()
            }
            for ref_num, ref_content in references
        ]
    
    # 9. 提取Image file信息
    image_match = re.search(r'\*Image file:\s*(.+?)\*', markdown_content)
    if image_match:
        parsed["image_file"] = image_match.group(1).strip()
    
    # 10. 提取Generated by信息
    generated_match = re.search(r'\*Generated by (.+?)\*', markdown_content)
    if generated_match:
        parsed["generated_by"] = generated_match.group(1).strip()
    
    return parsed


def main():
    """主函数"""
    print("=" * 80)
    print("按实体分类组织表格内容")
    print("=" * 80)
    
    # 配置路径（自动适配运行目录）
    # 如果从step3目录运行：python organize_tables_by_classification.py
    # 如果从根目录运行：python step3/organize_tables_by_classification.py
    if Path("./output/entity_filter_final_results.json").exists():
        # 从step3目录运行
        entity_results_file = Path("./output/entity_filter_final_results.json")
        output_base_dir = Path("./output")
    elif Path("./step3/output/entity_filter_final_results.json").exists():
        # 从根目录运行
        entity_results_file = Path("./step3/output/entity_filter_final_results.json")
        output_base_dir = Path("./step3/output")
    else:
        print("❌ 错误: 找不到 entity_filter_final_results.json")
        print("请确保：")
        print("  1. 已运行 entity_filter.py")
        print("  2. 在正确的目录下运行此脚本")
        return
    
    original_tables_dir = Path("data/step1/output/table_markdown_1/")
    
    # 检查输入文件是否存在
    if not entity_results_file.exists():
        print(f"❌ 错误: 结果文件不存在: {entity_results_file}")
        print("请先运行 entity_filter.py")
        return
    
    if not original_tables_dir.exists():
        print(f"❌ 错误: 原始表格目录不存在: {original_tables_dir}")
        return
    
    # 加载实体筛选结果
    print(f"\n📂 加载实体筛选结果: {entity_results_file}")
    results = load_json(entity_results_file)
    print(f"✅ 已加载 {len(results)} 个表格的结果")
    
    # 按分类统计（使用英文目录名）
    classification_stats = defaultdict(int)
    classification_tables = {
        "all_in": {},      # 全部在
        "partial_in": {},  # 部分在
        "none_in": {}      # 全都不在
    }
    
    # 中文到英文的映射
    chinese_to_english = {
        "全部在": "all_in",
        "部分在": "partial_in",
        "全都不在": "none_in"
    }
    
    # 分类表格
    print(f"\n🔍 开始分类表格...")
    for table_id, result in results.items():
        classification = result.get('classification', 'unknown')
        classification_stats[classification] += 1
        
        # 将中文分类映射到英文目录名
        english_category = chinese_to_english.get(classification)
        if english_category:
            classification_tables[english_category][table_id] = result
    
    # 显示统计
    print(f"\n📊 分类统计:")
    for category, count in classification_stats.items():
        percentage = (count / len(results)) * 100
        print(f"  - {category}: {count} ({percentage:.2f}%)")
    
    # 创建输出目录并保存
    print(f"\n📁 创建输出目录并保存表格内容...")
    
    for category, tables in classification_tables.items():
        if not tables:
            print(f"  ⚠️  {category}: 无表格，跳过")
            continue
        
        # 创建分类目录
        category_dir = output_base_dir / category
        category_dir.mkdir(parents=True, exist_ok=True)
        
        # 保存表格内容 - 每个表格一个单独的JSON文件
        success_count = 0
        failed_count = 0
        id_mapping = {}  # 记录数字编号与原始table_id的映射
        
        print(f"\n  处理 【{category}】 ({len(tables)} 个表格)...")
        
        table_number = 1  # 从1开始编号
        
        for table_id, result in tables.items():
            # 构建原始文件名：table_10 -> table_10.md
            file_name = f"{table_id}.md"
            original_file = original_tables_dir / file_name
            
            # 读取原始表格内容
            if original_file.exists():
                markdown_content = load_markdown(original_file)
                if markdown_content:
                    # 构建单个表格的数据 - 保留原始JSON的所有字段
                    table_data = dict(result)  # 复制所有原始字段
                    
                    # 解析markdown内容，提取各个部分
                    parsed_content = parse_markdown_table(markdown_content)
                    
                    # 添加额外的字段
                    table_data["table_id"] = table_id
                    table_data["number"] = table_number
                    table_data["markdown_content"] = markdown_content  # 保留完整的原始内容
                    table_data["file_path"] = str(original_file)
                    
                    # 添加解析后的结构化字段
                    table_data["parsed_content"] = parsed_content
                    
                    # 保存为单独的JSON文件，文件名为数字
                    output_file = category_dir / f"{table_number}.json"
                    save_json(table_data, output_file)
                    
                    # 记录映射关系（使用字符串作为键）
                    id_mapping[str(table_number)] = table_id
                    
                    success_count += 1
                    table_number += 1
                else:
                    failed_count += 1
            else:
                failed_count += 1
            
            # 进度提示
            if table_number % 1000 == 0:
                print(f"    进度: {table_number-1}/{len(tables)} ({(table_number-1)/len(tables)*100:.1f}%)")
        
        # 保存ID映射文件（数字编号 -> 原始table_id）
        mapping_file = category_dir / "id_mapping.json"
        save_json({
            "category": category,
            "total_count": success_count,
            "mapping": id_mapping,
            "description": "数字编号到原始table_id的映射关系"
        }, mapping_file)
        
        print(f"  ✅ {category}:")
        print(f"     - 成功: {success_count} 个")
        print(f"     - 失败: {failed_count} 个")
        print(f"     - 保存位置: {category_dir}")
        print(f"     - 文件命名: 1.json, 2.json, ..., {success_count}.json")
        print(f"     - ID映射文件: {mapping_file}")
    
    # 生成总体统计报告
    print(f"\n📋 生成总体统计报告...")
    summary = {
        "total_tables": len(results),
        "categories": {
            category: {
                "count": len(tables),
                "percentage": f"{len(tables)/len(results)*100:.2f}%"
            }
            for category, tables in classification_tables.items()
        },
        "output_directories": {
            "all_in": str(output_base_dir / "all_in"),
            "partial_in": str(output_base_dir / "partial_in"),
            "none_in": str(output_base_dir / "none_in")
        }
    }
    
    summary_file = output_base_dir / "classification_summary.json"
    save_json(summary, summary_file)
    print(f"  ✅ 统计报告: {summary_file}")
    
    # 最终总结
    print(f"\n" + "=" * 80)
    print("✅ 完成！")
    print("=" * 80)
    print(f"输出目录: {output_base_dir}")
    print(f"")
    print(f"目录结构:")
    print(f"  {output_base_dir}/")
    print(f"  ├── all_in/        (全部在)")
    print(f"  │   ├── 1.json")
    print(f"  │   ├── 2.json")
    print(f"  │   ├── 3.json")
    print(f"  │   ├── ...")
    print(f"  │   └── id_mapping.json       (数字编号到table_id的映射)")
    print(f"  ├── partial_in/    (部分在)")
    print(f"  │   ├── 1.json")
    print(f"  │   ├── 2.json")
    print(f"  │   ├── ...")
    print(f"  │   └── id_mapping.json")
    print(f"  ├── none_in/       (全都不在)")
    print(f"  │   ├── 1.json")
    print(f"  │   ├── 2.json")
    print(f"  │   ├── ...")
    print(f"  │   └── id_mapping.json")
    print(f"  └── classification_summary.json      (统计摘要)")
    print(f"")
    print(f"每个表格JSON文件 (1.json, 2.json, ...) 包含:")
    print(f"  基本信息:")
    print(f"    - table_id: 原始表格ID (如 table_12345)")
    print(f"    - number: 数字编号 (1, 2, 3, ...)")
    print(f"    - file_path: 原始文件路径")
    print(f"  完整内容:")
    print(f"    - markdown_content: 完整的原始Markdown内容")
    print(f"  实体分类信息:")
    print(f"    - classification: 分类结果")
    print(f"    - extracted_entities: 提取的实体类型")
    print(f"    - matched_entities: 匹配的实体")
    print(f"    - unmatched_entities: 未匹配的实体")
    print(f"    - reason: 分类原因")
    print(f"  结构化内容 (parsed_content):")
    print(f"    - table_title: 表格标题")
    print(f"    - source: 来源信息")
    print(f"    - page: 页码")
    print(f"    - table_identifier: 表格标识符")
    print(f"    - caption: 表格说明")
    print(f"    - table_content: 表格内容")
    print(f"    - mentioned_in_text: 文本引用")
    print(f"    - references: 参考文献列表")
    print(f"    - image_file: 图片文件名")
    print(f"    - generated_by: 生成工具")
    print(f"")
    print(f"id_mapping.json 文件包含:")
    print(f"  - 数字编号到原始table_id的完整映射关系")
    print(f"  - 方便根据数字编号查找原始表格ID")
    print("=" * 80)


if __name__ == "__main__":
    main()
